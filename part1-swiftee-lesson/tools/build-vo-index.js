#!/usr/bin/env node
// build-vo-index.js — lists the voice clips that exist, and how long each is.
'use strict';
const fs = require('node:fs'), path = require('node:path');
const crypto = require('node:crypto');
const { spawnSync } = require('node:child_process');

const li = process.argv.indexOf('--lang');
const LANG = li > 0 ? String(process.argv[li + 1] || '').replace(/[^a-z]/g, '') : '';
const dir = path.resolve(__dirname, '..', 'assets', 'vo', LANG);
const name = 'assets/vo/' + (LANG ? LANG + '/' : '');
fs.mkdirSync(dir, { recursive: true });
const clips = fs.readdirSync(dir).filter((f) => /\.ogg$/i.test(f)).map((f) => f.replace(/\.ogg$/i, '')).sort();

const revOf = (id) => {
  const h = crypto.createHash('md5');
  let any = false;
  ['.ogg'].forEach((ext) => {
    const f = path.join(dir, id + ext);
    if (!fs.existsSync(f)) return;
    any = true;
    h.update(fs.readFileSync(f));
  });
  return any ? h.digest('hex').slice(0, 8) : '';
};

const seconds = {};
const rev = {};
const spoken = {};
const speechEnd = (file, total) => {
  const r = spawnSync('ffmpeg', ['-hide_banner', '-i', file, '-af', 'silencedetect=noise=-40dB:d=0.15', '-f', 'null', '-'], { encoding: 'utf8' });
  const log = (r.stderr || '') + (r.stdout || '');
  const starts = [...log.matchAll(/silence_start: ([\d.]+)/g)].map((m) => parseFloat(m[1]));
  const ends = [...log.matchAll(/silence_end: ([\d.]+)/g)].map((m) => parseFloat(m[1]));
  if (!starts.length) return null;
  const last = starts[starts.length - 1];
  const trailing = ends.length < starts.length || Math.abs(ends[ends.length - 1] - total) < 0.08;
  return trailing && last > 0.1 ? Math.round(last * 1000) : null;
};
const wordMs = (() => {
  try { return JSON.parse(fs.readFileSync(path.join(dir, 'word-timings.json'), 'utf8')); }
  catch (e) { return {}; }
})();
let probed = 0;
clips.forEach((id) => {
  const r = spawnSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0',
                                  path.join(dir, id + '.ogg')], { encoding: 'utf8' });
  const d = parseFloat((r.stdout || '').trim());
  if (d > 0) {
    seconds[id] = Math.round(d * 100) / 100; probed++;
    const e = speechEnd(path.join(dir, id + '.ogg'), d);
    if (e) spoken[id] = e;
  }
  const v = revOf(id);
  if (v) rev[id] = v;
});

const words = {};
clips.forEach((id) => { if (Array.isArray(wordMs[id])) words[id] = wordMs[id]; });
fs.writeFileSync(path.join(dir, 'index.json'), JSON.stringify({ clips, seconds, rev, words, spoken }, null, 2) + '\n');
fs.writeFileSync(path.join(dir, 'index.js'),
  '/* generated by tools/build-vo-index.js from the same data as index.json — read only by a page opened off the disk (src/audio/vo.js) */\n' +
  'window.VO_INDEX = ' + JSON.stringify({ clips, seconds, rev, words, spoken }) + ';\n');
console.log(name + 'index.json  ' + clips.length + ' clip' + (clips.length === 1 ? '' : 's') +
            (probed ? ', ' + probed + ' timed' : ', no ffprobe — lengths unknown'));
